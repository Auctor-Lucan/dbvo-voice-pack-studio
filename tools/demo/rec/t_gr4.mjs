import { start } from './bridge.mjs';
import { OUT, sleep } from './shots_common.mjs';
const s = await start({ width: 1600, height: 940, scale: 1 }); const { page } = s;
await page.goto('https://app.dbvo/index.html');
const errs = []; page.on('pageerror', (e) => errs.push(e.message));
const results = []; const ok = (n, c, x = '') => results.push(`${c ? 'PASS' : 'FAIL'}  ${n}${x ? '  · ' + x : ''}`);
await page.waitForSelector('.home-cards');
const rpc = (m, p) => page.evaluate(([m, p]) => import('/lib.js').then((l) => l.rpc(m, p)), [m, p]);
const go = async (v, p) => { await page.evaluate(([v, p]) => import('/app.js').then((m) => m.go(v, p)), [v, p]); await sleep(1300); };
const st = await rpc('state', {});
const c = await rpc('grunts.create', { name: 'TTS test', target: 'spvs', slot: 'FemaleCustom02', voicePackId: st.voicePacks[0].id });
await go('grunt', { id: c.id });
await page.locator('.gr-tile:has(.gr-label:text-is("Attack"))').first().click(); await sleep(400);
await page.click('.inspector button:has-text("Text-to-speech")'); await sleep(600);
ok('Workspace opens for a combat grunt', await page.locator('#modal .gr-spoken').count() === 1);
await page.fill('#modal input[type=text] >> nth=0', 'Hyah!');
await page.fill('#modal .gr-spoken', 'Hyah!');
await page.locator('#modal .gr-spoken').click(); await page.keyboard.press('Home');
const chips = await page.locator('#modal .tag-chip').count();
if (chips) await page.locator('#modal .tag-chip').first().click();
const spokenVal = await page.inputValue('#modal .gr-spoken');
ok('Tag chip inserts at the cursor', !chips || spokenVal.startsWith('['), spokenVal);
await page.click('#modal button:has-text("Generate try")'); await sleep(2500);
await page.fill('#modal .gr-spoken', '[effortful grunt] HYAH!');
await page.locator('#modal .gr-spoken').press('Control+Enter'); await sleep(2500);
ok('Two tries, workspace still open', await page.locator('#modal .gr-try').count() === 2);
await page.screenshot({ path: `${OUT}/gr-tts-ws.png` });
await page.locator('#modal .gr-try').first().click(); await sleep(300);
await page.click('#modal button:has-text("Close")'); await sleep(1000);
let ev = (await rpc('grunts.get', { id: c.id })).events.find((e) => e.key === 'VanillaAttack');
ok('Close keeps tries, no line yet', ev.lines.length === 0 && ev.drafts[0].tries === 2, JSON.stringify(ev.drafts));
ok('Draft button in panel', await page.locator('.inspector .gr-draft').count() === 1);
await page.click('.inspector .gr-draft'); await sleep(800);
ok('Reopened with tries and text', await page.locator('#modal .gr-try').count() === 2 && (await page.inputValue('#modal .gr-spoken')) === '[effortful grunt] HYAH!');
ok('First try still picked', await page.locator('#modal .gr-try.sel b').innerText() === '#1');
await page.click('#modal button:has-text("Save to Attack")'); await sleep(1500);
ev = (await rpc('grunts.get', { id: c.id })).events.find((e) => e.key === 'VanillaAttack');
ok('Saved try is the line', ev.lines.length === 1 && ev.lines[0].text === 'Hyah!' && ev.lines[0].spoken.startsWith('['), JSON.stringify(ev.lines.map((l) => [l.text, l.spoken, l.origin])));
ok('Draft cleared', ev.drafts.length === 0);
// redo the line
await page.locator('.inspector .gr-line button:has-text("⋯")').click(); await sleep(300);
await page.click('.menu button:has-text("New tries")'); await sleep(700);
ok('Redo starts from the line texts', (await page.inputValue('#modal .gr-spoken')).startsWith('['));
await page.click('#modal button:has-text("Generate try")'); await sleep(2500);
await page.click('#modal button:has-text("Replace")'); await sleep(1500);
ev = (await rpc('grunts.get', { id: c.id })).events.find((e) => e.key === 'VanillaAttack');
ok('Replace keeps one line', ev.lines.length === 1, String(ev.lines.length));
await page.screenshot({ path: `${OUT}/gr-tts-after.png` });
await rpc('grunts.delete', { id: c.id });
ok('No page errors', errs.length === 0, errs.join(' / '));
console.log(results.join('\n'));
await s.close(); process.exit(0);
