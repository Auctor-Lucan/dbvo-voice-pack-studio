import { start } from './bridge.mjs';
import { OUT, sleep } from './shots_common.mjs';
const s = await start({ width: 1600, height: 940, scale: 1 }); const { page } = s;
await page.goto('https://app.dbvo/index.html');
const errs = []; page.on('pageerror', (e) => errs.push(e.message));
const results = []; const ok = (n, c, x = '') => results.push(`${c ? 'PASS' : 'FAIL'}  ${n}${x ? '  · ' + x : ''}`);
await page.waitForSelector('.home-cards'); await sleep(800);
await page.screenshot({ path: `${OUT}/v84-home.png` });
const titles = await page.locator('.home-card b').allInnerTexts();
ok('Home cards', titles[4] && titles[4].includes('character') && titles[5].includes('lip sync'), titles.join(' | '));
const rpc = (m, p) => page.evaluate(([m, p]) => import('/lib.js').then((l) => l.rpc(m, p)), [m, p]);
const go = async (v, p) => { await page.evaluate(([v, p]) => import('/app.js').then((m) => m.go(v, p)), [v, p]); await sleep(1500); };
const gl = await rpc('grunts.list', {}); const g = gl.find((x) => x.lines > 0);
await go('grunt', { id: g.id });
await page.locator('.gr-tile.st-full').first().click(); await sleep(500);
await page.click('.gr-line button:has-text("⋯")'); await sleep(250);
await page.click('.menu button:has-text("Effect…")'); await sleep(500);
ok('Effect tiles, custom slots, no retired', await page.locator('#modal .fx-tile.empty').count() === 3 && await page.locator('#modal .fx-tile:has-text("Robotic")').count() === 0);
await page.screenshot({ path: `${OUT}/v84-fx.png` });
await page.keyboard.press('Escape'); await sleep(300);
const rl = await rpc('revoice.list', {});
await go('revoice', { id: rl[0].id }); await page.click('.view-head button:has-text("Lines")').catch(() => {}); await sleep(1200);
ok('Revoice: no Language in the toolbar', await page.locator('.vbar label:text-is("Language"), .vbar .tgroup:has(label:text-is("Language"))').count() === 0);
await page.locator('.vgrid .vrow input[type=checkbox]').nth(1).click().catch(() => {}); await sleep(300);
await page.screenshot({ path: `${OUT}/v84-rv.png` });
ok('Effects button', await page.locator('button:has-text("Effects ▾")').count() === 1);
await page.click('button:has-text("Effects ▾")'); await sleep(300);
await page.locator('.menu button:has-text("Hall")').click(); await sleep(2500);
ok('E icon on the line', await page.locator('.vgrid .fx-e').count() >= 1, String(await page.locator('.vgrid .fx-e').count()));
await page.screenshot({ path: `${OUT}/v84-rv2.png` });
await page.locator('.vgrid .fx-e').first().click(); await sleep(2500);
ok('E click removes', await page.locator('.vgrid .fx-e').count() === 0);
ok('No page errors', errs.length === 0, errs.join(' / '));
console.log(results.join('\n'));
await s.close(); process.exit(0);
