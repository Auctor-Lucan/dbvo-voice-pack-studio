import { start } from './bridge.mjs';
import { OUT, sleep } from './shots_common.mjs';
const W = 1920;
const s = await start({ width: W, height: 1040, scale: 1 }); const { page } = s;
await page.goto('https://app.dbvo/index.html');
const errs = []; page.on('pageerror', (e) => errs.push(e.message));
const results = []; const ok = (n, c, x = '') => results.push(`${c ? 'PASS' : 'FAIL'}  ${n}${x ? '  · ' + x : ''}`);
await page.waitForSelector('.home-cards');
const rpc = (m, p) => page.evaluate(([m, p]) => import('/lib.js').then((l) => l.rpc(m, p)), [m, p]);
const go = async (v, p) => { await page.evaluate(([v, p]) => import('/app.js').then((m) => m.go(v, p)), [v, p]); await sleep(1300); };
const st = await rpc('state', {});
const mod = st.mods.find((m) => m.name === 'Skyrim');
const before = (await rpc('mod.get', { id: mod.id })).plugins[0];
await go('mod', { id: mod.id }); await sleep(700);
await page.click('.filter-chips .chip:has-text("Alias lines")'); await sleep(500);
const n = await page.locator('.vrow').count();
ok('Alias lines filter', n >= 1, String(n));
await page.locator('.vrow .iter-chip').first().click(); await sleep(600);
ok('Iterations dialog opens with the alias field', await page.locator('#modal .field-label.mono').count() >= 1, await page.locator('#modal .field-label.mono').first().innerText().catch(() => ''));
await page.locator('#modal input[placeholder^="e.g. Whiterun"]').first().fill('Ralof, Hadvar, the Jarl');
await sleep(400);
const sum = await page.locator('#modal .fr-sum').innerText();
ok('Counts the iterations', /3 iteration/.test(sum), sum);
await page.screenshot({ path: `${OUT}/v78-iter.png` });
await page.click('#modal .btn.primary'); await sleep(1000);
const after = (await rpc('mod.get', { id: mod.id }));
const line = after.plugins[0].lines.find((l) => (l.variants || []).length);
ok('Iterations saved, line unchanged', line && line.variants.length === 3 && line.original.includes('<Alias'), line ? line.variants.join(' | ') + ' // final: ' + line.final : 'none');
ok('Alias values remembered', JSON.stringify(after.aliasValues).includes('Hadvar'), JSON.stringify(after.aliasValues));
ok('Topic file grows by 3', after.plugins[0].topicLines === before.topicLines + 3, `${before.topicLines} → ${after.plugins[0].topicLines}`);
ok('Grid shows 3 iter.', /3 iter/.test(await page.locator('.vrow').first().innerText()));
await page.screenshot({ path: `${OUT}/v78-grid.png` });
// undo
await rpc('line1.setIterations', { modId: mod.id, plugin: before.fileName, mode: 'replace', items: [{ k: line.key, v: [] }] });
ok('No page errors', errs.length === 0, errs.join(' / '));
console.log(results.join('\n'));
await s.close(); process.exit(0);
