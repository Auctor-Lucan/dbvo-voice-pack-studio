import { start } from './bridge.mjs';
import { OUT, sleep } from './shots_common.mjs';
const s = await start({ width: 1600, height: 940, scale: 1 }); const { page } = s;
await page.goto('https://app.dbvo/index.html'); await page.waitForSelector('.home-cards');
const rpc = (m, p) => page.evaluate(([m, p]) => import('/lib.js').then((l) => l.rpc(m, p)), [m, p]);
const go = async (v, p) => { await page.evaluate(([v, p]) => import('/app.js').then((m) => m.go(v, p)), [v, p]); await sleep(1500); };
const st = await rpc('state', {});
const a = st.patches[0];
const pa = await rpc('patch.get', { id: a.id });
const nb = await rpc('patch.create', { voicePackId: st.voicePacks[st.voicePacks.length - 1].id, modIds: pa.modIds || a.modIds, name: 'Second voice', kind: 'tts' });
const edited = pa.lines.filter((l) => l.spokenEdited).length;
await go('patch', { id: nb.id });
await page.click('button:has-text("Import ▾")'); await sleep(300);
await page.click('.menu button:has-text("Spoken text from another patch")'); await sleep(1500);
await page.locator('#modal select').selectOption(a.id); await sleep(1200);
await page.screenshot({ path: `${OUT}/v85-import.png` });
console.log('PREVIEW', (await page.locator('#modal .box').innerText()).split('\n')[0], 'edited in source', edited);
await page.click('#modal .btn.primary'); await sleep(1500);
const pb = await rpc('patch.get', { id: nb.id });
console.log('AFTER', pb.lines.filter((l) => l.spokenEdited).length);
const words = await rpc('patch.importSpoken', { id: nb.id, fromId: a.id, which: 'edited', keepMine: false, scope: 'all', tags: 'words', preview: true });
console.log('WORDS preview changed', words.changed, JSON.stringify(words.samples[0] || {}));
await s.close(); process.exit(0);
