import { start } from './bridge.mjs';
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const s = await start({ width: 1600, height: 950, scale: 1 }); const { page } = s;
page.on('pageerror', (e) => console.log('PAGEERR', e.message));
await page.exposeFunction('__note', (t) => console.log(t));
await page.goto('https://app.dbvo/index.html'); await page.waitForSelector('.home-cards');
await page.evaluate(() => { let last = ''; const o = new MutationObserver(() => { const j = document.getElementById('job'); const b = document.querySelector('.busy-chip'); const t = `job ${j.classList.contains('hidden') ? 'hidden' : 'shown'}: ${j.querySelector('.job-label').textContent} | chip ${b && !b.classList.contains('hidden') ? b.textContent : '-'}`; if (t !== last) { last = t; window.__note(Date.now() % 100000 + ' ' + t); } }); o.observe(document.querySelector('header') || document.body, { attributes: true, childList: true, subtree: true, characterData: true }); });
await page.evaluate(() => import('/app.js').then((m) => m.go('fomods'))); await sleep(800);
await page.locator('button:has-text("New FOMOD")').first().click(); await sleep(400);
await page.locator('#modal input[type=text]').first().fill('Bar test ' + Date.now());
await page.click('#modal button:has-text("Create")'); await sleep(1200);
await page.click('button:has-text("Add DBVO Patches")'); await sleep(500);
await page.locator('#modal label.row', { hasText: 'Skyrim' }).locator('input').check(); await page.click('#modal .btn.primary'); await sleep(1500);
await page.locator('.fedit .path-input input').nth(1).fill('D:\\DBVO\\Releases'); await page.locator('.fedit .path-input input').nth(1).dispatchEvent('change'); await sleep(700);
console.log(Date.now() % 100000, 'build click');
await page.click('button:has-text("Build")'); await sleep(300);
await page.click('.menu button:has-text("Build and pack")');
await sleep(8000);
console.log('modal:', await page.locator('#modal').textContent().catch(() => ''));
await page.screenshot({ path: 'buildbar.png' });
await s.close(); process.exit(0);
