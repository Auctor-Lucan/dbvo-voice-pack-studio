import { sleep, waitJob, genPick } from './shots_common.mjs';
export async function run(s, S) {
  const { page } = s;
  const step = async (name, fn) => { try { await fn(); } catch (e) { console.log('STEP FAIL', name, e.message.split('\n')[0]); await page.keyboard.press('Escape').catch(() => {}); } };
  await step('fomod', async () => {
    await page.click('button.crumb[data-section="fomods"]'); await sleep(800);
    await S.full('phase3-empty');
    await page.locator('button:has-text("+ New FOMOD")').first().click(); await sleep(600);
    await page.locator('#modal input[type=text]').nth(0).fill('DBVO Sample Voice');
    await S.modal('phase3-new');
    await page.click('#modal button:has-text("Create")'); await sleep(1200);
    await page.click('button:has-text("+ Add DBVO Patches")'); await sleep(700);
    await S.modal('phase3-addpatches');
    await page.click('#modal button:has-text("Add")'); await sleep(1200);
    await page.locator('.fnode.opt').first().click(); await sleep(600);
    await S.full('phase3-option');
    await page.locator('.fnode.opt').nth(1).click(); await sleep(600);
    await S.full('phase3-option2');
    await page.locator('.fnode:has-text("DBVO voice pack JSON")').click(); await sleep(500);
    await S.full('phase3-json');
    await page.locator('.fnode:has-text("Installer & info.xml")').click(); await sleep(500);
    const ver = page.locator('.scard:has(.scard-lbl > span:text-is("Version")) input').first(); await ver.fill('1.0'); await sleep(300);
    const au = page.locator('.scard:has(.scard-lbl > span:text-is("Author")) input').first(); await au.fill('Your Name'); await sleep(300);
    await S.full('phase3-installer');
    await page.click('button:has-text("Validate")'); await sleep(900);
    await S.modal('phase3-validate');
    await page.keyboard.press('Escape'); await page.locator('#modal .btn').last().click().catch(() => {}); await sleep(400);
    await page.click('button:has-text("Simulate install")'); await sleep(1500);
    await S.modal('phase3-simulate');
    await page.keyboard.press('Escape'); await page.locator('#modal .btn').last().click().catch(() => {}); await sleep(400);
    await page.click('button:has-text("Build ▾")'); await sleep(400);
    await S.full('phase3-build-menu');
    await page.click('text=Build and pack'); await sleep(800);
    await page.waitForFunction(() => document.querySelector('#job')?.classList.contains('hidden') && document.querySelector('#modal:not(.hidden)'), null, { timeout: 60000 }); await sleep(600);
    await S.modal('phase3-built');
    await page.locator('#modal .btn.primary').first().click(); await sleep(500);
  });
  await step('revoice', async () => {
    await page.click('#tools-btn'); await sleep(400);
    await S.full('tools-menu');
    await page.click('text=Replace NPC voice files in any mod'); await sleep(1000);
    await S.full('revoice-list');
    await page.click('.prow:has-text("Example Town")'); await sleep(1200);
    await page.click('.seg button:has-text("Setup"), button:has-text("Setup")'); await sleep(800);
    await S.full('revoice-setup');
    await page.click('button:has-text("Speakers (")'); await sleep(1500);
    await S.full('revoice-speakers');
    await page.click('button:has-text("Lines (")'); await sleep(1500);
    await page.locator('.vrow:has-text("Put that back")').first().click(); await sleep(600);
    await S.full('revoice-lines');
    await page.click('button:has-text("New voice types (")'); await sleep(800);
    await S.full('revoice-voicetypes');
  });
  await step('wavlip', async () => {
    await page.click('#tools-btn'); await sleep(400);
    await page.click('text=Whisper listens to WAV files'); await sleep(1000);
    s.pick('D:\\Recordings\\Extra lines');
    await page.click('button:has-text("Add folder…")'); await sleep(1500);
    await S.full('wavlip-queued');
    await page.click('button:has-text("Transcribe + Generate .LIP")'); await sleep(500);
    await page.waitForFunction(() => /Done|done|finished/i.test(document.querySelector('.tool-log')?.innerText || ''), null, { timeout: 60000 }).catch(() => {});
    await sleep(1500);
    await S.full('wavlip-done');
  });
  await step('credits', async () => {
    await page.click('[data-section="settings"]'); await sleep(600);
    await page.click('.nav-item:has-text("Credits")'); await sleep(800);
    await S.full('settings-credits');
    await page.click('.nav-item:has-text("Omit references")'); await sleep(600);
    await S.full('settings-references');
  });
  await step('landing', async () => {
    await page.click('#brand'); await page.waitForSelector('.home-cards'); await sleep(1500);
    await S.full('landing');
    await page.click('.home-rc:has-text("Skyrim")'); await page.waitForSelector('.statusbar .gen-btn'); await sleep(900);
    await page.locator('.toolbar .help-btn').click(); await page.waitForSelector('.help-drawer'); await sleep(700);
    await S.full('help-drawer');
    await page.keyboard.press('Escape'); await sleep(300);
    if (await page.locator('.help-drawer').count()) console.log('STEP FAIL drawer did not close');
    await page.click('[data-section="help"]'); await page.waitForSelector('.help-toc'); await sleep(1200);
    await S.full('help-page');
    await page.fill('.help-search input', 'fuz report'); await sleep(600);
    await S.full('help-search');
    await page.click('[data-section="settings"]'); await sleep(700);
    await page.click('.nav-item:has-text("General & tools")'); await sleep(700);
    await page.locator('.section:has(h2:text-is("Start page"))').scrollIntoViewIfNeeded();
    await S.el('settings-startpage', '.section:has(h2:text-is("Start page"))');
  });
}
