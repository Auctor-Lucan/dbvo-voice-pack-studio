import { start } from './bridge.mjs';
import { OUT, sleep } from './shots_common.mjs';
const s = await start({ width: 1920, height: 1040, scale: 1 }); const { page } = s;
await page.goto('https://app.dbvo/index.html');
const errs = []; page.on('pageerror', (e) => errs.push(e.message));
const results = []; const ok = (n, c, x = '') => results.push(`${c ? 'PASS' : 'FAIL'}  ${n}${x ? '  · ' + x : ''}`);
await page.waitForSelector('.home-cards');
const rpc = (m, p) => page.evaluate(([m, p]) => import('/lib.js').then((l) => l.rpc(m, p)), [m, p]);
const go = async (v, p) => { await page.evaluate(([v, p]) => import('/app.js').then((m) => m.go(v, p)), [v, p]); await sleep(1300); };
await rpc('settings.save', { settings: { ui: { readSize: 'largest' } } });
await page.evaluate(() => import('/app.js').then((m) => m.refreshState()));
const st = await rpc('state', {});
const sky = st.patches.find((p) => p.name === 'Skyrim');
await go('patch', { id: sky.id }); await page.waitForSelector('.vrow');
ok('QA column header', await page.locator('.vgrid-head .cell:has-text("QA")').count() === 1);
await page.click('.statusbar button:has-text("Check takes")'); await sleep(600);
const box = await page.locator('#modal .modal-card').boundingBox();
ok('Dialog fits at Large', box.height < 1000, `${Math.round(box.height)} px tall`);
await page.screenshot({ path: `${OUT}/v801-qa.png` });
await page.locator('#modal .qa-opt:has-text("Words") .switch, #modal .qa-opt:has-text("Words") input').first().click(); await sleep(200);
await page.locator('#modal button:has-text("All")').click().catch(() => {});
await page.click('#modal .btn.primary'); await sleep(5000);
await page.locator('.vgrid-head .cell:has-text("QA")').click(); await sleep(500);
const first = await page.locator('.vrow').first().locator('.qa-badge').innerText().catch(() => '');
ok('QA sort puts flagged first', first === '⚠', first);
await page.screenshot({ path: `${OUT}/v801-grid.png`, clip: { x: 900, y: 250, width: 1020, height: 400 } });
await page.locator('.vgrid-head .cell:has-text("QA")').click(); await page.locator('.vgrid-head .cell:has-text("QA")').click(); await sleep(300);
await rpc('settings.save', { settings: { ui: { readSize: 'larger' } } });
ok('No page errors', errs.length === 0, errs.join(' / '));
console.log(results.join('\n'));
await s.close(); process.exit(0);
