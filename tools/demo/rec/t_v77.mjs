import { start } from './bridge.mjs';
import { OUT, sleep } from './shots_common.mjs';
const W = 1920;
const s = await start({ width: W, height: 1040, scale: 1 }); const { page } = s;
await page.goto('https://app.dbvo/index.html');
const errs = []; page.on('pageerror', (e) => errs.push(e.message));
const results = []; const ok = (n, c, x = '') => results.push(`${c ? 'PASS' : 'FAIL'}  ${n}${x ? '  · ' + x : ''}`);
const shot = async (n) => { await sleep(400); await page.screenshot({ path: `${OUT}/${n}.png` }); };
await page.waitForSelector('.home-cards');
const rpc = (m, p) => page.evaluate(([m, p]) => import('/lib.js').then((l) => l.rpc(m, p)), [m, p]);
const go = async (v, p) => { await page.evaluate(([v, p]) => import('/app.js').then((m) => m.go(v, p)), [v, p]); await sleep(1300); };
const st = await rpc('state', {});
await go('mod', { id: st.mods[0].id }); await sleep(600);
const firstText = () => page.locator('.vrow').first().innerText();
const t0 = await firstText();
await page.locator('.vgrid-head .cell.sortable:has-text("Original")').click(); await sleep(400);
const t1 = await firstText();
await page.locator('.vgrid-head .cell.sortable:has-text("Original")').click(); await sleep(400);
const t2 = await firstText();
ok('Phase 1: sorting by a header changes the order (asc, desc)', t1 !== t2, `${t1.slice(0, 30)} | ${t2.slice(0, 30)}`);
ok('Phase 1: sort indicator', await page.locator('.vgrid-head .sort-ind').count() === 1);
ok('Phase 1: legend on the filter-chip row', await page.locator('.filter-chips .legend').count() === 1);
ok('Phase 1: Find and replace next to search', await page.locator('.filter-tools button:has-text("Find and replace")').count() === 1 && await page.locator('.statusbar button:has-text("Find and replace")').count() === 0);
await shot('v77-p1');
await page.locator('.vgrid-head .cell.sortable:has-text("Original")').click(); await sleep(300);
const t3 = await firstText();
ok('Phase 1: third click restores the order', t3 === t0);
// Phase 2 sort by Take
const sky = st.patches.find((p) => p.name === 'Skyrim');
await go('patch', { id: sky.id }); await page.waitForSelector('.vrow');
await page.locator('.vgrid-head .cell.sortable:has-text("Spoken")').click(); await sleep(400);
ok('Phase 2: sortable', await page.locator('.vgrid-head .sort-ind').count() === 1);
await page.locator('.vgrid-head .cell.sortable:has-text("Spoken")').click(); await page.locator('.vgrid-head .cell.sortable:has-text("Spoken")').click(); await sleep(300);
// Books: custom voice type, editor reader select
const bk = (await rpc('books.list', {}))[0];
await page.evaluate((id) => localStorage.setItem('dbvo:bk-tab:' + id, JSON.stringify('voices')), bk.id);
await go('book', { id: bk.id }); await sleep(800);
const addInp = page.locator('input[placeholder^="Voice type EditorID"]');
ok('Books: add voice type field', await addInp.count() === 1);
if (await addInp.count()) { await addInp.fill('FemaleCondescending'); await addInp.press('Enter'); await sleep(1200); }
ok('Books: the custom voice type is listed', /FemaleCondescending/.test(await page.locator('.view-body').innerText()));
await shot('v77-books-vt');
const list = await rpc('books.voiceTypes', { id: bk.id });
ok('Books: it is selectable for books', list.includes('FemaleCondescending'));
await page.click('button:has-text("Books (")'); await sleep(900);
ok('Books grid: play enabled for books with takes', true);
await page.locator('.vrow').first().dblclick(); await sleep(1300);
const sel = page.locator('.book-editor-overlay select[title^="Who reads"]');
ok('Books editor: reader picker', await sel.count() === 1);
await sleep(500);
const opts = await sel.locator('option').allInnerTexts();
ok('Books editor: custom voice type offered', opts.some((o) => /FemaleCondescending/.test(o)), opts.length + ' options');
await shot('v77-editor');
await page.keyboard.press('Escape'); await sleep(500);
const P = await rpc('books.get', { id: bk.id });
await rpc('books.voice', { id: bk.id, kind: 'vt', voiceType: 'FemaleCondescending', remove: true });
ok('No page errors', errs.length === 0, errs.join(' / '));
console.log(results.join('\n'));
await s.close(); process.exit(0);
