// Video 3: NPC Revoice: one NPC, a new voice type, and a big mod.
import { start } from './bridge.mjs';
import { overlay, makeDriver, startCapture, sleep } from './driver.mjs';

const OUT = process.env.OUT || 'frames_v3';
const s = await start();
const { page } = s;
await page.goto('https://app.dbvo/index.html');
await page.waitForSelector('.home-checks');
await overlay(page);
const d = makeDriver(page);
await d.fade(true);
const cap = process.env.NOCAP ? { pause() {}, resume() {}, async stop() { return 0; } } : await startCapture(page, OUT);
let k = 0;
const shot = () => (process.env.SHOTS ? page.screenshot({ path: `v3_${k++}.png` }) : null);
const until = (fn, t = 240000) => page.waitForFunction(fn, null, { timeout: t, polling: 100 });
const jobDone = () => until(() => document.querySelector('#job')?.classList.contains('hidden'));
let capAt = 0, capHold = 0;
const say = async (kick, text) => { const w = capAt + capHold - Date.now(); if (w > 0) await sleep(w); await d.caption(kick, text); capAt = Date.now(); capHold = Math.max(3200, text.length * 62); };
const settle = async () => { const w = capAt + capHold - Date.now(); if (w > 0) await sleep(w); };
const pickVoice = async (speaker, name) => {
  const sel = page.locator(`tr:has(td:has-text("${speaker}"))`).first().locator('select').nth(1);
  const v = await sel.locator(`option:has-text("${name}")`).first().getAttribute('value');
  await d.select(sel, v, { pause: 250 });
};

// ---------------------------------------------------------------- intro
await sleep(400);
await d.fade(false);
await say('NPC Revoice Tool', 'The NPC Revoice Tool gives NPCs new voices, in any mod or in the base game itself.');
await d.click('#tools-btn', { pause: 700 });
await d.hover('.menu >> text=NPC Revoice Tool', 900);
await d.click('.menu >> text=NPC Revoice Tool', { pause: 1200 });
await say('NPC Revoice Tool', 'It swaps out the voice files line by line, keeping their names, so the game never needs a plugin.');
await say('NPC Revoice Tool', 'A project starts with a mod\'s plugin and its voice archive. Here are two: a quiet town and a sprawling quest mod.');
await d.hover('.prow:has-text("Example Town")', 1600);
await d.hover('.prow:has-text("Hollow Crown")', 1600);
await shot();

// ---------------------------------------------------------------- one NPC
await say('One NPC', 'Let\'s start small, with one NPC. Open Example Town revoiced.');
await d.click('.prow:has-text("Example Town")', { pause: 1200 });
await d.click('button:has-text("Setup")', { pause: 600 }).catch(() => {});
await say('Setup', 'Setup holds the plugin and the voice archive. The scan found every line, and the voice file it plays.');
await d.hover('.section:has-text("Plugins") .section-head, .section:has-text("Plugins")', 1400).catch(() => {});
await d.hover('.section:has-text("Scan")', 1400).catch(() => {});
await say('Speakers', 'The Speakers tab shows who says what: one row per NPC, or per voice type when several NPCs share a line.');
await d.click('button:has-text("Speakers (")', { pause: 900 });
await d.hover('tr:has-text("Hilde") td >> nth=0', 1200).catch(() => {});
await d.hover('tr:has-text("FemaleNord (shared)") td >> nth=0', 1400).catch(() => {});
await say('Speakers', 'Hilde the smith has a voice picked. Gunnar and the shared lines don\'t, so they keep the voices they have.');
await d.hover('tr:has-text("Hilde") select >> nth=1', 1600).catch(() => {});
await d.hover('tr:has-text("Gunnar") select >> nth=1', 1400).catch(() => {});
await shot();
await say('Lines', 'The Lines tab shows every line: who speaks it, the subtitle, and what the new voice will say.');
await d.click('button:has-text("Lines (")', { pause: 900 });
await d.hover('.vrow:has-text("Need something sharpened")', 1400);
await say('Lines', 'Emotions stored in the plugin turn into suggested audio tags. One tick accepts a suggestion.');
for (const t of ['father ran this forge', 'lose my temper', 'always breaks']) await d.click(page.locator(`.vrow:has-text("${t}") button[title^="Accept"]`).first(), { pause: 600 }).catch(() => {});
await sleep(400);
await shot();
await say('Generate', 'Generate options, then Missing. Only Hilde has a voice, so only her seven lines get made.');
await d.click('button:has-text("Generate options")', { pause: 700 });
await d.click('.gen-pop .gen-item:has-text("Missing")', { pause: 900 });
await say('Generate', 'One last check before credits are spent: who gets voiced, how many characters, and which settings.');
await d.hover('#modal .kv, #modal', 1600).catch(() => {});
await d.click('#modal .btn.primary', { pause: 200 });
await say('Generate', 'Every line gets a fresh take, and a LIP file to go with it.');
await d.move({ x: 1000, y: 560 });
await jobDone();
await sleep(800);
await shot();

// ---------------------------------------------------------------- new voice type
await say('New voice type', 'There\'s a catch. Hilde shares the FemaleNord voice type with Ingrid and Sigrun, so lines like Hello there belong to all three.');
await d.hover('.vrow:has-text("Hello there.")', 1800);
await say('New voice type', 'For those shared lines to sound like her too, Hilde needs a voice type of her own.');
await d.click('button:has-text("New voice types")', { pause: 900 });
await say('New voice type', 'This tab explains when you need one, and what it writes.');
await d.hover('.help', 1600);
await say('New voice type', 'Give an NPC a new voice type: search for Hilde, and pick her.');
await d.click('button:has-text("Give an NPC a new voice type")', { pause: 900 });
await d.clickType('#modal input[type=text]', 'Hilde', { delay: 90 });
await sleep(700);
await d.click('#modal label:has-text("Hilde")', { pause: 500 });
await d.click('#modal button:has-text("Create")', { pause: 1400 });
await say('New voice type', 'The new voice type gets its own EditorID. Every copy of Hilde in your plugins is listed, so replacer mods keep her voice.');
await d.hover('#modal input[type=text] >> nth=0', 1400).catch(() => {});
await d.hover('#modal .field-label:has-text("NPC records")', 1400).catch(() => {});
await say('New voice type', 'The form lists that unlock dialogue for her old voice type are offered too, and you choose which lines to generate.');
await d.hover('#modal .field-label:has-text("Form lists")', 1400).catch(() => {});
await d.hover('#modal .field-label:has-text("Lines to generate")', 1400).catch(() => {});
await shot();
await d.click('#modal button:has-text("Save")', { pause: 900 });
await say('New voice type', 'Export, then Only the new voice type pack, writes the files that switch her over.');
await d.click('button:has-text("Export .fuz")', { pause: 700 });
await d.hover('.menu >> text=Only the new voice type pack', 1000);
await d.click('.menu >> text=Only the new voice type pack', { pause: 1000 });
await page.waitForSelector('#modal:not(.hidden)');
await say('New voice type', 'That\'s an ESL plugin holding just the voice type, a SkyPatcher file that gives it to Hilde, and a FormList Manipulator file.');
await d.hover('#modal pre, #modal .box', 1400).catch(() => {});
await say('New voice type', 'There are no NPC or list overrides, so other mods\' edits to Hilde keep working.');
await shot();
await d.click('#modal .btn.primary', { pause: 500 });
await say('Export', 'Export fuz files puts every take into the game\'s own voice folders, replacing what\'s there.');
await d.click('button:has-text("Export .fuz")', { pause: 600 });
await d.hover('.menu >> text=Export .fuz files to the output folder', 1600);
await page.keyboard.press('Escape');
await sleep(400);

// ---------------------------------------------------------------- big mod
await say('A whole mod', 'Now for something bigger: The Hollow Crown, a large quest mod.');
await d.click('button:has-text("← NPC Revoice"), button:has-text("NPC Revoice")', { pause: 900 });
await d.click('.prow:has-text("Hollow Crown")', { pause: 1200 });
await d.click('button:has-text("Setup")', { pause: 600 });
await say('A whole mod', 'The scan found 1,239 lines, each with the voice file it plays today.');
await d.hover('.section:has-text("Scan") .section-body, .section:has-text("Scan")', 1600).catch(() => {});
await shot();
await say('A whole mod', 'Fifteen speakers, each needing a voice from your ElevenLabs account or a local engine.');
await d.click('button:has-text("Speakers (")', { pause: 900 });
await say('A whole mod', 'Time to cast them: the queen, the noble, the priestess and the captain.');
await pickVoice('Queen Ysolde', 'Regal Queen');
await pickVoice('Lord Varric', 'Cold Noble');
await pickVoice('Sister Maelis', 'Stern Priestess');
await pickVoice('Captain Hrolf', 'Gruff Captain');
await sleep(500);
await shot();
await say('A whole mod', 'Every row tracks progress and characters left. Anyone you\'d rather leave alone can be skipped.');
await d.hover('tr:has-text("Queen Ysolde") td >> nth=3', 1400).catch(() => {});
await d.hover('tr:has-text("Old Bjarni") td >> nth=6', 1400).catch(() => {});
await say('A whole mod', 'All 1,239 lines sit in one list: filter by speaker, search, and add tags in bulk.');
await d.click('button:has-text("Lines (")', { pause: 900 });
await d.scrollWheel('.vrow >> nth=8', 1600, 14);
await sleep(600);
await say('A whole mod', 'Generate the whole cast in one go: 545 lines for the four voiced speakers. The rest wait their turn.');
await d.click('button:has-text("Generate options")', { pause: 700 });
await d.click('.gen-pop .gen-item:has-text("Missing")', { pause: 900 });
await d.hover('#modal .kv, #modal', 1800).catch(() => {});
await shot();
await d.click('#modal .btn.primary', { pause: 200 });
await d.move({ x: 1000, y: 560 });
await settle();
await sleep(1500);
cap.pause();
await jobDone();
await sleep(500);
cap.resume();
await say('A whole mod', 'Done: 545 new lines, LIP files included, ready to export.');
await d.hover('button:has-text("Export .fuz")', 1600);
await d.click('button:has-text("Speakers (")', { pause: 900 });
await say('A whole mod', 'Four speakers finished, eleven still waiting for their audition.');
await d.hover('text=4 finished', 1600).catch(() => {});
await shot();
await say('NPC Revoice Tool', 'One NPC or a whole mod, plus a new voice type for anyone who needs one.');
await settle();
await d.uncaption();
await d.fade(true);
await sleep(300);
const n = await cap.stop();
console.log('frames', n);
await s.close();
process.exit(0);
