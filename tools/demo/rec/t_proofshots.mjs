import { start } from './bridge.mjs';
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const O = process.env.OUTP;
const s = await start({ width: 1400, height: 900, scale: 2 }); const { page } = s;
await page.goto('https://app.dbvo/index.html'); await page.waitForSelector('.home-cards');
const rpc = (m, p) => page.evaluate(([m, p]) => import('/lib.js').then((l) => l.rpc(m, p)), [m, p]);
const st = await rpc('state', {});
const M = st.mods.find((m) => m.name === 'Skyrim');
const mod = await rpc('mod.get', { id: M.id }); const pl = mod.plugins[0];
const typos = ['Will killing some bandits will make you feel better?', 'Khajiit does not like this place. Too many walls, not enough sky.', 'Dont worry <Alias=Player>, I\'ll handle it myself.'];
const vis = pl.lines.filter((l) => l.status !== 'Removed' && l.kind === 'Valid').slice(0, typos.length);
for (let i = 0; i < vis.length; i++) await rpc('line1.update', { modId: M.id, plugin: pl.fileName, key: vis[i].key, action: 'setFinal', value: typos[i] });
await page.evaluate((id) => import('/app.js').then((m) => m.go('mod', { id })), M.id); await sleep(1500);
await page.getByText('Proofread…').click(); await sleep(600);
await page.locator('.modal-card').screenshot({ path: `${O}/g_setup.png` });
await page.getByRole('button', { name: 'Start →' }).click(); await sleep(1800);
await page.locator('.pr-edit').evaluate((e) => e.blur());
await page.locator('.modal-card').screenshot({ path: `${O}/g_sugg.png` });
await page.keyboard.press('Control+Enter'); await sleep(500); await page.locator('.pr-edit').evaluate((e) => e.blur());
await page.locator('.modal-card').screenshot({ path: `${O}/g_style.png` });
await page.keyboard.press('Control+Enter'); await sleep(500); await page.locator('.pr-edit').evaluate((e) => e.blur());
await page.locator('.modal-card').screenshot({ path: `${O}/g_tag.png` });
await page.keyboard.press('Alt+a'); await sleep(200); await page.keyboard.press('Control+Enter'); await sleep(500);
await sleep(2500);
await page.locator('.modal-card').screenshot({ path: `${O}/g_sum.png`, timeout: 3000 }).catch((e) => console.log('no summary'));
await page.keyboard.press('Escape'); await sleep(300);
const p2 = (await rpc('mod.get', { id: M.id })).plugins[0];
for (const l of vis) { await rpc('line1.update', { modId: M.id, plugin: pl.fileName, key: l.key, action: 'revert' }); await rpc('line1.update', { modId: M.id, plugin: pl.fileName, key: l.key, action: 'fix', value: null }); }
for (const l of p2.lines.filter((l) => l.proofread)) await rpc('line1.update', { modId: M.id, plugin: pl.fileName, key: l.key, action: 'unproofread' });
process.exit(0);
