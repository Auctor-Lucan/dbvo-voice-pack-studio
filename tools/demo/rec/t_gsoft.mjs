import { start } from './bridge.mjs';
import { sleep } from './driver.mjs';
const s = await start(); const { page } = s;
await page.goto('https://app.dbvo/index.html'); await sleep(1500);
const rpc = (m, p) => page.evaluate(([m, p]) => import('/lib.js').then((l) => l.rpc(m, p)), [m, p]);
const g = (await rpc('grunts.list', {}))[0];
const d = await rpc('grunts.get', { id: g.id });
const ev = d.events.find((e) => e.lines.length);
const l = ev.lines[0];
let r = await rpc('grunts.effect', { id: g.id, lineIds: [l.id], effect: '', soften: true });
let l2 = r.project.events.find((e) => e.id === ev.id).lines[0];
console.log('soften on:', l2.soften, l2.reverb);
r = await rpc('grunts.effect', { id: g.id, lineIds: [l.id], effect: 'cave' });
l2 = r.project.events.find((e) => e.id === ev.id).lines[0];
console.log('cave keeps soften:', l2.soften, l2.effectId);
r = await rpc('grunts.effect', { id: g.id, lineIds: [l.id], effect: '', soften: false });
l2 = r.project.events.find((e) => e.id === ev.id).lines[0];
console.log('off:', l2.soften, l2.reverb);
const pv = await rpc('grunts.fxPreview', { id: g.id, lineId: l.id, effect: '', soften: true }); console.log('preview', !!pv.url);
await s.close(); process.exit(0);
