import { start } from './bridge.mjs';
import { OUT, sleep } from './shots_common.mjs';
const s = await start({ width: 1920, height: 1040, scale: 1 }); const { page } = s;
await page.goto('https://app.dbvo/index.html');
const errs = []; page.on('pageerror', (e) => errs.push(e.message));
const results = []; const ok = (n, c, x = '') => results.push(`${c ? 'PASS' : 'FAIL'}  ${n}${x ? '  · ' + x : ''}`);
await page.waitForSelector('.home-cards');
const rpc = (m, p) => page.evaluate(([m, p]) => import('/lib.js').then((l) => l.rpc(m, p)), [m, p]);
const go = async (v, p) => { await page.evaluate(([v, p]) => import('/app.js').then((m) => m.go(v, p)), [v, p]); await sleep(1300); };
const st = await rpc('state', {});
const mod = st.mods.find((m) => m.name === 'Skyrim');
const m0 = await rpc('mod.get', { id: mod.id });
ok('No line hidden after opening', m0.plugins.every((p) => p.lines.every((l) => !l.hiddenByPrompts)));
const line = m0.plugins[0].lines.find((l) => l.hasOtherAlias && !l.isPlayerName);
await go('mod', { id: mod.id }); await sleep(700);
ok('Status bar has the iterations button', /Iterations for/.test(await page.locator('.statusbar').innerText()));
await rpc('line1.setIterations', { modId: mod.id, plugin: m0.plugins[0].fileName, mode: 'replace', items: [{ k: line.key, v: ['Take this to Ralof in Whiterun.'] }] });
await go('home'); await go('mod', { id: mod.id }); await sleep(700);
const badge = await page.locator(`.vrow:has-text("Alias=Recipient") .badge`).first().innerText();
ok('Label', /ITERATIONS ADDED|Fixed/.test(badge), badge);
await rpc('line1.setIterations', { modId: mod.id, plugin: m0.plugins[0].fileName, mode: 'replace', items: [{ k: line.key, v: [] }] });
const sky = st.patches.find((p) => p.name === 'Skyrim');
await go('patch', { id: sky.id }); await page.waitForSelector('.vrow');
await page.click('.statusbar button:has-text("Export")'); await sleep(400);
const menu = await page.locator('.pop-panel, .menu').last().innerText();
ok('Export menu has WAV + LIP only', /WAV \+ LIP only/.test(menu), menu.split('\n').slice(0, 4).join(' | '));
await page.screenshot({ path: `${OUT}/v791-export.png`, clip: { x: 900, y: 500, width: 1020, height: 540 } });
ok('No page errors', errs.length === 0, errs.join(' / '));
console.log(results.join('\n'));
await s.close(); process.exit(0);
