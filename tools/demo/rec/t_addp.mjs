import { start } from './bridge.mjs';
import { sleep } from './driver.mjs';
const s = await start();
const { page } = s;
page.on('pageerror', (e) => console.log('PAGEERR', e.message));
await page.goto('https://app.dbvo/index.html');
const shot = (n) => page.screenshot({ path: `addp_${n}.png` });
await page.waitForSelector('.home-cards');
await page.evaluate(() => import('/app.js').then((m) => m.go('fomods'))); await sleep(1000);
await page.locator('button:has-text("New FOMOD")').first().click(); await sleep(500);
await page.locator('#modal input[type=text]').first().fill('Test addp ' + Date.now());
await page.click('#modal button:has-text("Create")'); await sleep(1200);
await page.click('button:has-text("Add DBVO Patches")'); await sleep(600);
console.log('ticked at open', await page.locator('#modal input[type=checkbox]:checked').count(), 'of', await page.locator('#modal input[type=checkbox]').count());
await shot('1open');
await page.click('#modal button:has-text("Tick new ones")'); await sleep(200);
console.log('after tick', await page.locator('#modal input[type=checkbox]:checked').count(), await page.locator('#modal .btn.primary').textContent());
await page.fill('#modal input[placeholder^="Find"]', 'zzz'); await sleep(200);
console.log('filtered rows', await page.locator('#modal label.row').count());
await page.fill('#modal input[placeholder^="Find"]', ''); await sleep(200);
await page.click('#modal button:has-text("Untick all")');
console.log('after untick', await page.locator('#modal input[type=checkbox]:checked').count(), await page.locator('#modal .btn.primary').textContent());
await page.locator('#modal input[type=checkbox]').first().check(); await sleep(100);
await shot('2one');
await page.click('#modal .btn.primary'); await sleep(1500);
await shot('3tree');
await page.getByText('Skyrim', { exact: true }).locator('visible=true').first().click(); await sleep(800);
console.log(await page.locator('textarea').first().inputValue());
await shot('4opt');
await s.close(); process.exit(0);
