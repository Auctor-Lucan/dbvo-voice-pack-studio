import { start } from './bridge.mjs';
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const s = await start({ width: 1600, height: 950, scale: 1 }); const { page } = s;
await page.goto('https://app.dbvo/index.html'); await page.waitForSelector('.home-cards');
const rpc = (m, p) => page.evaluate(([m, p]) => import('/lib.js').then((l) => l.rpc(m, p)), [m, p]);
const st = await rpc('state', {});
const M = st.mods.find((m) => m.name === 'Skyrim');
const mod = await rpc('mod.get', { id: M.id }); const pl = mod.plugins[0];
await page.evaluate((id) => import('/app.js').then((m) => m.go('mod', { id })), M.id); await sleep(1500);
const valid = pl.lines.filter((l) => l.kind === 'Valid' && l.status !== 'Removed' && !l.excluded);
const a = valid[0], b = valid[1];
await page.evaluate(() => { for (const t of ['pointerdown', 'mousedown', 'focusout', 'change', 'pointerup', 'mouseup', 'click']) document.addEventListener(t, (e) => console.log('EV', t, e.target.className || e.target.tagName, e.target.isConnected), true);
  const mo = new MutationObserver((ms) => { for (const m of ms) for (const n of m.removedNodes) if (n.nodeType === 1) console.log('REMOVED', n.className); }); mo.observe(document.querySelector('.vgrid, .grid, #view') || document.body, { childList: true, subtree: true }); });
page.on('console', (m) => { if (m.text().startsWith('EV') || m.text().startsWith('REMOVED')) console.log(m.text()); });
const row = (key) => page.locator(`.vrow[data-key="${key}"]`);
await row(a.key).locator('input[type=text]').first().click(); await page.keyboard.press('End'); await page.keyboard.type(' Typed');
console.log('--- click');
const btn = row(b.key).locator('button.appr').first();
const bb = await btn.boundingBox();
await page.mouse.move(bb.x + bb.width / 2, bb.y + bb.height / 2);
await page.mouse.down(); await sleep(130); await page.mouse.up(); await sleep(800);
await rpc('line1.update', { modId: M.id, plugin: pl.fileName, key: a.key, action: 'revert' });
process.exit(0);
