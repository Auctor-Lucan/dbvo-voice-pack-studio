// Video 6: the WAV to LIP Tool.
import { start } from './bridge.mjs';
import { overlay, makeDriver, startCapture, sleep } from './driver.mjs';

const OUT = process.env.OUT || 'frames_v6';
const s = await start();
const { page } = s;
await page.goto('https://app.dbvo/index.html');
await page.waitForSelector('.home-checks');
await overlay(page);
const d = makeDriver(page);
await d.fade(true);
const cap = process.env.NOCAP ? { pause() {}, resume() {}, async stop() { return 0; } } : await startCapture(page, OUT);
let k = 0;
const shot = () => (process.env.SHOTS ? page.screenshot({ path: `v6_${k++}.png` }) : null);
let capAt = 0, capHold = 0;
const say = async (kick, text) => { const w = capAt + capHold - Date.now(); if (w > 0) await sleep(w); await d.caption(kick, text); capAt = Date.now(); capHold = Math.max(3200, text.length * 62); };
const settle = async () => { const w = capAt + capHold - Date.now(); if (w > 0) await sleep(w); };
const until = (fn, t = 180000) => page.waitForFunction(fn, null, { timeout: t, polling: 100 });

await sleep(400);
await d.fade(false);
await say('WAV to LIP Tool', 'Skyrim\'s lip sync needs the words. A LIP file is made from the audio plus the exact text being spoken.');
await d.click('#tools-btn', { pause: 900 });
await d.hover('.menu >> text=WAV to LIP Tool', 1200);
await d.click('.menu >> text=WAV to LIP Tool', { pause: 1400 });
await say('WAV to LIP Tool', 'But your own recordings, voice-changed lines and files from other tools often come with no text at all.');
await sleep(2600);
s.pick('D:\\Recordings\\Extra lines');
await d.click('button:has-text("Add folder…")', { pause: 1200 });
await d.hover('.vrow >> nth=0, tbody tr >> nth=0', 1600).catch(() => sleep(1600));
await shot();
await say('WAV to LIP Tool', 'So Whisper listens first and writes down what\'s said. That transcript is what FaceFXWrapper works from.');
await sleep(2600);
await d.click('button:has-text("Transcribe + Generate .LIP")', { pause: 600 });
await d.click('#modal .btn.primary', { pause: 300 }).catch(() => {});
await d.move({ x: 900, y: 520 });
await until(() => document.querySelector('#job')?.classList.contains('hidden'));
await sleep(900);
await shot();
await say('WAV to LIP Tool', 'Every file gets its words and a matching LIP file next to it, in bulk. No typing, no transcript to check by hand.');
await d.hover('text=The road north is closed', 1800).catch(() => sleep(1800));
await d.hover('text=Mind the step', 1800).catch(() => sleep(1800));
await say('WAV to LIP Tool', 'Whisper is built in. There\'s nothing to install, and it runs on your graphics card or the CPU.');
await sleep(3000);
await shot();
await settle();
await d.uncaption();
await d.fade(true);
await sleep(300);
const n = await cap.stop();
console.log('frames', n);
await s.close();
process.exit(0);
