// Extra guide shots for 7.3: the Generate options panels and the FOMOD installer with its build summary.
import { boot, shooter, sleep } from './shots_common.mjs';
const s = await boot(); const { page } = s; const S = shooter(page);
await page.waitForSelector('.home-cards');
const rpc = (m, p) => page.evaluate(([m, p]) => import('/lib.js').then((l) => l.rpc(m, p)), [m, p]);
const go = async (v, p) => { await page.evaluate(([v, p]) => import('/app.js').then((m) => m.go(v, p)), [v, p]); await sleep(1300); };
const st = await rpc('state', {});
const sky = st.patches.find((p) => p.name === 'Skyrim');
await go('patch', { id: sky.id }); await page.waitForSelector('.vrow');
await page.locator('.vrow').nth(2).click(); await sleep(500);
await S.right('phase2-panel', 520);
await page.click('.statusbar .gen-btn'); await sleep(400);
await S.el('phase2-genpanel', '.pop-panel');
await page.keyboard.press('Escape'); await sleep(300);
const rv = (await rpc('revoice.list', {}))[0];
await go('revoice', { id: rv.id });
await page.click('button:has-text("Lines (")'); await sleep(800);
await page.locator('.vrow').nth(1).click(); await sleep(500);
await S.full('revoice-lines');
await page.click('.statusbar .gen-btn'); await sleep(400);
await S.el('revoice-genpanel', '.pop-panel');
await page.keyboard.press('Escape'); await sleep(300);
await page.click('button:has-text("Speakers (")'); await sleep(900);
await S.full('revoice-speakers');
const fm = (await rpc('state', {})).fomods[0];
await go('fomod', { id: fm.id });
await page.locator('.fnode:has-text("Installer & info.xml")').click(); await sleep(1500);
await page.locator('.fomod-summary button:has-text("Validate")').click(); await sleep(900);
await page.locator('#modal .btn').last().click().catch(() => {}); await sleep(600);
await S.full('phase3-installer');
await s.close(); process.exit(0);
