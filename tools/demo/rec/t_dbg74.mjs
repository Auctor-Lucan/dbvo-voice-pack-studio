import { start } from './bridge.mjs';
import { sleep } from './shots_common.mjs';
const s = await start({ width: 1920, height: 1040, scale: 1 }); const { page } = s;
await page.goto('https://app.dbvo/index.html');
page.on('pageerror', (e) => console.log('PAGEERR', e.message));
await page.waitForSelector('.home-cards');
const rpc = (m, p) => page.evaluate(([m, p]) => import('/lib.js').then((l) => l.rpc(m, p)), [m, p]);
const bk = (await rpc('books.list', {}))[0];
await page.evaluate((id) => localStorage.setItem('dbvo:bk-tab:' + id, JSON.stringify('books')), bk.id);
await page.evaluate((id) => import('/app.js').then((m) => m.go('book', { id })), bk.id); await sleep(1500);
await page.locator('.vrow:has-text("Roads of the Old North")').first().dblclick(); await sleep(1200);
console.log('A overlay', await page.locator('.book-editor-overlay').count());
await page.keyboard.press('Escape'); await sleep(800);
console.log('B overlay after Esc (clean)', await page.locator('.book-editor-overlay').count());
await page.locator('.vrow:has-text("Roads of the Old North")').first().dblclick(); await sleep(1200);
await page.locator('.ed-tools input[placeholder="[custom tag]"]').fill('whispers');
await page.locator('.ed-tools input[placeholder="[custom tag]"]').press('Enter'); await sleep(300);
console.log('focus', await page.evaluate(() => document.activeElement.className));
await page.keyboard.press('Escape'); await sleep(800);
console.log('C overlay', await page.locator('.book-editor-overlay').count(), 'modal', await page.locator('#modal').getAttribute('class'), await page.locator('#modal').innerText().catch(() => ''));
await s.close(); process.exit(0);
