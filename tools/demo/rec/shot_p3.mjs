import { boot, sleep } from './shots_common.mjs';
const s = await boot(); const { page } = s;
await page.waitForSelector('.home-cards');
const rpc = (m, p) => page.evaluate(([m, p]) => import('/lib.js').then((l) => l.rpc(m, p)), [m, p]);
const st = await rpc('state', {});
const sky = st.mods.find((m) => m.name === 'Skyrim');
await rpc('mod.saveMeta', { id: sky.id, version: '1.6.1170', nexusUrl: 'https://www.nexusmods.com/skyrimspecialedition/mods/000000' });
await page.evaluate(() => import('/app.js').then((m) => m.go('fomods'))); await sleep(800);
await page.locator('button:has-text("New FOMOD")').first().click(); await sleep(500);
await page.locator('#modal input[type=text]').first().fill('DBVO Sample Voice');
await page.click('#modal button:has-text("Create")'); await sleep(1200);
await page.click('button:has-text("Add DBVO Patches")'); await sleep(700);
await page.locator('#modal label.row').filter({ hasText: /^Skyrim\s*Misc/ }).first().locator('input').check();
await page.click('#modal .btn.primary'); await sleep(1500);
await page.locator('.fnode:has-text("Installer & info.xml")').click(); await sleep(500);
const card = (t) => page.locator(`.scard:has(.scard-lbl > span:text-is("${t}")) input`).first();
await card('Version').fill('1.0'); await card('Author').fill('Your Name');
const root = card('FOMOD root folder'); await root.fill('D:\\DBVO\\Sample Voice\\FOMOD'); await root.dispatchEvent('change');
const rel = card('Release folder'); await rel.fill('D:\\DBVO\\Releases'); await rel.dispatchEvent('change');
await sleep(1200);
await page.screenshot({ path: 'g_installer.png' });
await page.locator('.fnode.opt', { hasText: 'Skyrim' }).last().click(); await sleep(700);
await page.screenshot({ path: 'g_option.png' });
await page.click('button:has-text("Build ▾")'); await sleep(300);
await page.click('.menu button:has-text("Build and pack")');
await page.waitForSelector('#modal .modal-card:has-text("FOMOD built")', { timeout: 60000 }); await sleep(500);
await page.locator('#modal .modal-card').screenshot({ path: 'g_built.png' });
console.log(await page.locator('#modal .modal-card').innerText());
await s.close(); process.exit(0);
